/**
 * Large dotted text: 7 lines, each letter 5 dots wide. Unknown characters render as a space.
 * @param {string} text
 * @param {import('./symbols.mjs').Glyphs} g
 */
export function bigText(text, g) {
  const letters = [...text.toUpperCase()].map((ch) => FONT[/** @type {keyof typeof FONT} */ (ch)] ?? FONT[' '])
  return Array.from({ length: 7 }, (_, r) => letters.map((rows) => [...rows[r]].map((b) => (b === '#' ? g.dot : ' ')).join(' ')).join('   '))
}
